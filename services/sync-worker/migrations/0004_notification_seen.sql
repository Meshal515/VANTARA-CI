-- B9 — الإشعارات داخل التطبيق: حالة ثلاثية بدل حالتين.
--
-- `read` وحده لا يكفي. التنبيه الجانبي يجب أن يظهر مرة واحدة لا عند كل مزامنة،
-- وبلا علامة «عُرض» لا توجد طريقة للتمييز بين إشعار وصل الآن وإشعار ظهر ومرّ
-- ولم يفتحه المستخدم بعد. النتيجة كانت ستكون أحد أمرين: تنبيه يتكرر كل 60 ثانية
-- إلى أن يُفتح، أو اعتبار العرض قراءةً فيختفي غير المقروء بلا أن يراه أحد.
--
-- `seen` = عُرض التنبيه أو فُتح الصندوق. `read` = فتح المستخدم الإشعار نفسه.
-- عدّاد غير المقروء يقرأ `read` وحده: العرض ليس قراءة.

ALTER TABLE notifications ADD COLUMN seen INTEGER NOT NULL DEFAULT 0;

-- صندوق مستخدم واحد مرتّبًا بالأحدث، وعدّ غير المقروء: كلاهما على هذا الفهرس
CREATE INDEX IF NOT EXISTS notifications_inbox
  ON notifications (user_id, read, created_at);

-- الصفوف السابقة: المقروء عُرض ضمنًا، وغير المقروء يبقى «وصل» فيظهر تنبيهه مرة.
UPDATE notifications SET seen = 1 WHERE read = 1;
