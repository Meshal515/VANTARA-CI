-- B4 — تقدم القراءة مرآة مُقرّة، لا حقيقة ثانية.
--
-- القارئ يكتب تقدمه في مكانين: عند Uchiyomi (المالك) وفي هذا الجدول. لا شيء
-- كان يصالح الاثنين. فإذا نجحت كتابة D1 وفشلت كتابة المالك — شبكة، أو جلسة
-- محتوى منتهية، أو الـAPI ساقط — عاد القارئ للصفحة الأولى عند الفتح التالي
-- بينما الصفحة 30 محفوظة هنا، والإحصائيات تقول إن الفصل قُرئ. ولا أحد يعرف
-- أي الرقمين الحقيقي.
--
-- `owner_synced` يجعل الجواب صريحًا: 0 يعني «المالك لم يستلم هذه القيمة بعد»،
-- فهي صادرة تُدفَع إليه ثم تُقرّ. 1 يعني أنه أقرّها، فهو المرجع وهذه مرآة له.
-- بلا هذا العمود لا يمكن التمييز بين تقدم لم يصل المالك وتقدم تجاوزه المالك.

ALTER TABLE progress ADD COLUMN owner_synced INTEGER NOT NULL DEFAULT 0;

-- الصفوف المعلّقة قليلة والجدول ينمو بعدد الفصول المقروءة؛ فهرس جزئي يجعل
-- تصريف الصندوق قراءةً واحدة رخيصة عند كل إقلاع.
CREATE INDEX IF NOT EXISTS progress_pending
  ON progress (user_id, updated_at)
  WHERE owner_synced = 0;

-- الصفوف الموجودة قبل هذا التعديل مجهولة الحالة. الافتراض الآمن هو «غير مُقرّة»:
-- دفعها للمالك لا يُرجعه للخلف أبدًا (reconcileProgress يدمج بـmax)، بينما
-- افتراض الإقرار كان سيجعل تقدمًا لم يصله يُمحى بقيمته الأقدم.
UPDATE progress SET owner_synced = 0;
